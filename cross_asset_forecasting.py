"""Leakage-controlled forecasting benchmark on the full cross-asset panel.

This consumes ``data/extension/cross_asset_panel.csv`` generated by
``run_cross_asset_extension.py``. Unlike the original four-index benchmark,
each market group is treated as an entity, so the model can learn from the
equity, crypto, international, financial, energy, and technology histories
that are already present in the repository.

Run from the project root with ``py -3.12 cross_asset_forecasting.py``.
"""
from __future__ import annotations

import json
import random
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import torch
from sklearn.metrics import average_precision_score, brier_score_loss, f1_score, roc_auc_score
from sklearn.preprocessing import StandardScaler
from torch import nn
from torch.utils.data import DataLoader, TensorDataset

ROOT = Path(__file__).resolve().parent
PANEL_FILE = ROOT / "data" / "extension" / "cross_asset_panel.csv"
OUT = ROOT / "data" / "forecasting"
SEQUENCE_LENGTH = 20
SEED = 17
FOLDS = [
    ("test_2011_2015", "2011-01-01", "2015-12-31"),
    ("test_2016_2020", "2016-01-01", "2020-12-31"),
    ("test_2021_plus", "2021-01-01", "2100-01-01"),
]


class CrashLSTM(nn.Module):
    def __init__(self, n_features: int, hidden: int = 24):
        super().__init__()
        self.lstm = nn.LSTM(n_features, hidden, batch_first=True)
        self.head = nn.Sequential(nn.LayerNorm(hidden), nn.Dropout(0.2), nn.Linear(hidden, 1))

    def forward(self, x):
        _, (h, _) = self.lstm(x)
        return self.head(h[-1]).squeeze(-1)


def load_panel() -> tuple[pd.DataFrame, list[str]]:
    frame = pd.read_csv(PANEL_FILE, parse_dates=["date"])
    required = {"market_group", "date", "crash_label_N15"}
    missing = required - set(frame.columns)
    if missing:
        raise ValueError(f"Panel is missing required columns: {sorted(missing)}")
    feature_names = [c for c in frame.columns if c.startswith(("TDA_", "CSD_"))]
    if not feature_names:
        raise ValueError("Panel does not contain TDA_ or CSD_ feature columns")
    frame = frame.dropna(subset=["market_group", "date", *feature_names, "crash_label_N15"]).copy()
    frame["crash_label_N15"] = frame["crash_label_N15"].astype(int)
    return frame.sort_values(["market_group", "date"]).reset_index(drop=True), feature_names


def sequences(frame: pd.DataFrame, feature_names: list[str], mode: str):
    if mode == "tda":
        chosen = [c for c in feature_names if c.startswith("TDA_")]
    elif mode == "classical":
        chosen = [c for c in feature_names if c.startswith("CSD_")]
    else:
        chosen = feature_names
    xs, ys, dates, groups = [], [], [], []
    for group_name, group in frame.groupby("market_group", sort=False):
        group = group.sort_values("date").reset_index(drop=True)
        values = group[chosen].to_numpy(np.float32)
        labels = group["crash_label_N15"].to_numpy(np.float32)
        for end in range(SEQUENCE_LENGTH - 1, len(group)):
            xs.append(values[end - SEQUENCE_LENGTH + 1:end + 1])
            ys.append(labels[end])
            dates.append(group.loc[end, "date"])
            groups.append(group_name)
    return np.stack(xs), np.asarray(ys), pd.to_datetime(dates), np.asarray(groups), chosen


def threshold(probabilities: np.ndarray) -> float:
    return float(np.quantile(probabilities, 0.95, method="higher"))


def metrics(y: np.ndarray, p: np.ndarray, cutoff: float) -> dict:
    predicted = p >= cutoff
    return {
        "n": int(len(y)),
        "positives": int(y.sum()),
        "prevalence": float(y.mean()),
        "average_precision": float(average_precision_score(y, p)) if y.sum() else np.nan,
        "roc_auc": float(roc_auc_score(y, p)) if len(np.unique(y)) > 1 else np.nan,
        "brier": float(brier_score_loss(y, p)),
        "threshold": float(cutoff),
        "precision": float(np.sum(predicted & (y == 1)) / max(predicted.sum(), 1)),
        "recall": float(np.sum(predicted & (y == 1)) / max(y.sum(), 1)),
        "f1": float(f1_score(y, predicted, zero_division=0)),
        "alarms": int(predicted.sum()),
    }


def fit_predict(x, y, train_idx, val_idx, test_idx, epochs=20):
    scaler = StandardScaler()
    scaler.fit(x[train_idx].reshape(-1, x.shape[-1]))
    scaled = scaler.transform(x.reshape(-1, x.shape[-1])).reshape(x.shape).astype(np.float32)
    positives = max(float(y[train_idx].sum()), 1.0)
    negatives = max(float(len(train_idx) - y[train_idx].sum()), 1.0)
    model = CrashLSTM(x.shape[-1])
    optimizer = torch.optim.AdamW(model.parameters(), lr=8e-4, weight_decay=1e-3)
    loss_fn = nn.BCEWithLogitsLoss(pos_weight=torch.tensor(min(negatives / positives, 20.0)))
    loader = DataLoader(
        TensorDataset(torch.from_numpy(scaled[train_idx]), torch.from_numpy(y[train_idx])),
        batch_size=512,
        shuffle=True,
    )
    best_ap, best_state, stale = -1.0, None, 0
    for _ in range(epochs):
        model.train()
        for batch_x, batch_y in loader:
            optimizer.zero_grad(set_to_none=True)
            loss = loss_fn(model(batch_x), batch_y)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
        model.eval()
        with torch.no_grad():
            validation_p = torch.sigmoid(model(torch.from_numpy(scaled[val_idx]))).numpy()
        ap = average_precision_score(y[val_idx], validation_p) if y[val_idx].sum() else 0.0
        if ap > best_ap + 1e-5:
            best_ap = ap
            best_state = {key: value.detach().clone() for key, value in model.state_dict().items()}
            stale = 0
        else:
            stale += 1
            if stale >= 4:
                break
    if best_state is not None:
        model.load_state_dict(best_state)
    model.eval()
    with torch.no_grad():
        validation_p = torch.sigmoid(model(torch.from_numpy(scaled[val_idx]))).numpy()
        test_p = torch.sigmoid(model(torch.from_numpy(scaled[test_idx]))).numpy()
    return model, scaler, test_p, threshold(validation_p)


def main() -> None:
    random.seed(SEED)
    np.random.seed(SEED)
    torch.manual_seed(SEED)
    torch.set_num_threads(1)
    OUT.mkdir(parents=True, exist_ok=True)
    frame, feature_names = load_panel()
    rows, final_models = [], {}
    for fold, test_start, test_end in FOLDS:
        start, end = pd.Timestamp(test_start), pd.Timestamp(test_end)
        train_end = start - pd.Timedelta(days=25)
        val_start = train_end - pd.DateOffset(years=2)
        for mode in ("classical", "tda", "combined"):
            x, y, dates, groups, chosen = sequences(frame, feature_names, mode)
            train_idx = np.flatnonzero(dates < val_start - pd.Timedelta(days=25))
            val_idx = np.flatnonzero((dates >= val_start) & (dates <= train_end))
            test_idx = np.flatnonzero((dates >= start) & (dates <= end))
            if min(len(train_idx), len(val_idx), len(test_idx)) == 0:
                continue
            model, scaler, test_p, cutoff = fit_predict(x, y, train_idx, val_idx, test_idx)
            result = metrics(y[test_idx], test_p, cutoff)
            result.update(
                fold=fold, model=f"LSTM_{mode}", train_start=dates[train_idx].min().date(),
                train_end=dates[train_idx].max().date(), test_start=dates[test_idx].min().date(),
                test_end=dates[test_idx].max().date(), feature_count=len(chosen),
                group_count=len(np.unique(groups[test_idx])),
            )
            rows.append(result)
            print(f"{fold} {mode}: n_train={len(train_idx)} n_test={len(test_idx)} "
                  f"groups={result['group_count']} AP={result['average_precision']:.4f}", flush=True)
            if fold == "test_2021_plus":
                final_models[mode] = (model, scaler, chosen, cutoff)
    results = pd.DataFrame(rows)
    results.to_csv(OUT / "cross_asset_walk_forward_metrics.csv", index=False)
    for mode, (model, scaler, chosen, cutoff) in final_models.items():
        torch.save(
            {"state_dict": model.state_dict(), "feature_names": chosen,
             "sequence_length": SEQUENCE_LENGTH, "threshold": cutoff,
             "hidden_size": 24, "market_groups": sorted(frame.market_group.unique())},
            OUT / f"cross_asset_{mode}_lstm.pt",
        )
        joblib.dump(scaler, OUT / f"cross_asset_{mode}_scaler.joblib")
    report = [
        "Leakage-controlled full cross-asset crash forecast",
        f"Input rows: {len(frame)}; groups: {frame.market_group.nunique()}",
        f"Group rows: {frame.groupby('market_group').size().to_dict()}",
        "Labels and features come from the precomputed extension panel; each group is sequenced independently.",
        "A 25-calendar-day separation purges overlapping 15-session targets at validation and test boundaries.",
        "The warning threshold is the validation 95th percentile, targeting approximately 5% alert days.",
        f"Positive share: {frame.groupby('market_group').crash_label_N15.mean().round(4).to_dict()}",
    ]
    (OUT / "cross_asset_forecasting_report.txt").write_text("\n".join(report), encoding="utf-8")
    print("\nAggregate test-block results:")
    print(results.groupby("model")[["average_precision", "roc_auc", "brier", "precision", "recall", "f1"]].mean().round(4))


if __name__ == "__main__":
    main()
